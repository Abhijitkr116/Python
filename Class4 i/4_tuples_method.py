a = (1, 45, 9, 4, 72, False, "Hello", 3.14, 4)

b = a.count(4) # Return the number of times "4" appears in the tuple
c = a.index(4) # Return the index of the first occurrence of "4"

print(f"Number of times 4 appears in tuple a: {b}")
print(f"Index of first occurrence of 4: {c}")
print(f"Length of tuple a: {len(a)}") # Return the length of the tuple